export function Sidebar() {
  const pathname = usePathname();
  const { profile } = useUser();

  function navLink(item: NavItem) {
    const active = pathname === item.href || pathname.startsWith(item.href + "/");
    return (
      <Link
        key={item.href}
        href={item.href}
        className={`flex items-center gap-3 rounded-lg px-3 py-2 text-sm font-medium transition-colors ${
          active
            ? "bg-tera-50 text-tera-700"
            : "text-text-secondary hover:bg-surface-secondary hover:text-text-primary"
        }`}
      >
        {item.icon}
        {item.label}
      </Link>
    );
  }

  return (
    <aside className="hidden w-60 shrink-0 border-r border-border bg-surface p-4 lg:block">
      <nav className="space-y-1">
        {askerNav.map(navLink)}

        {profile?.is_helper ? (
          <>
            <div className="pb-1 pt-4">
              <p className="px-3 text-xs font-semibold uppercase tracking-wider text-text-muted">
                Helper
              </p>
            </div>
            {helperNav.map(navLink)}
          </>
        ) : (
          <Link
            href="/helper/onboarding"
            className="flex items-center gap-3 rounded-lg px-3 py-2 text-sm font-medium text-tera-600 hover:bg-tera-50 transition-colors"
          >
            <svg className="h-5 w-5" fill="none" viewBox="0 0 24 24" strokeWidth={1.5} stroke="currentColor">
              <path strokeLinecap="round" strokeLinejoin="round" d="M12 4.5v15m7.5-7.5h-15" />
            </svg>
            Become a helper
          </Link>
        )}

        <div className="pb-1 pt-4">
          <p className="px-3 text-xs font-semibold uppercase tracking-wider text-text-muted">
            Account
          </p>
        </div>
        {settingsNav.map(navLink)}
      </nav>
    </aside>
  );
}
